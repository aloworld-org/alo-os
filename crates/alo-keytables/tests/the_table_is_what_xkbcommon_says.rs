/// One row of `how-to-type`'s table, as a keycode and the modifiers held.
///
/// **The modifiers are read from between the brackets and the layout name is
/// never counted past**, because a layout name contains spaces — *English
/// (US)* — so splitting the line on whitespace and taking the sixth field
/// reads a level number on one layout and a bracket on another.
fn a_way_to_type_it(line: &str) -> Option<(u16, Held)> {
    use alo_keytables::what_is_held_down::{ALT_GR, CAPS_LOCK, LEFT_SHIFT};

    let (before, modifiers) = line.split_once('[')?;
    let modifiers = modifiers.strip_suffix(']').unwrap_or(modifiers);

    let xkb_keycode: u16 = before.split_whitespace().next()?.parse().ok()?;
    let keycode = xkb_keycode.checked_sub(8)?;

    let mut held = Held::nothing();
    for named in modifiers.split_whitespace() {
        held = match named {
            "Shift" => held.and_this_went_down(LEFT_SHIFT),
            "Lock" => held.and_this_went_down(CAPS_LOCK),
            "Mod5" => held.and_this_went_down(ALT_GR),
            // Control, Mod1 and the rest do not change what a key types, and a
            // row needing one of them is not a way to type the character.
            _ => return None,
        };
    }
    Some((keycode, held))
}

/// Whether this keysym puts no character anywhere.
///
/// Four kinds, and each is here for a reason rather than to quieten a check:
///
/// - **modifiers and the keypad's own actions** — they change or they move, and
///   type nothing;
/// - **dead keys** — a dead key composes, which is `alo-keyboards`' chain and
///   not this crate's, and by itself it types nothing;
/// - **editing and navigation**, including the `Undo`, `Redo`, `Find`, `Help`,
///   `Cancel` and `Menu` keys that exist on real keyboards and are requests
///   rather than characters;
/// - **input-method switches** — `Hangul`, `Hiragana`, `Katakana`,
///   `Henkan_Mode`, `Muhenkan` — which choose how text is entered.
///   `alo-keyboards` carries input methods and this crate does not.
///
/// The braille dots are the group worth naming twice: a braille keyboard sends
/// them in combination and the character *is* the combination, so no single one
/// of them has a character of its own.
///
/// **Nothing is added here to make a check pass.** A name reaching this list is
/// a claim that nobody pressing that key expects a letter, and if that were
/// wrong of one of them, the eight tables would be short of a key with nothing
/// to say so.
fn types_nothing(keysym: &str) -> bool {
    const PREFIXES: [&str; 14] = [
        "dead_", "ISO_", "XF86", "KP_", "Shift", "Control", "Alt", "Super", "Meta", "Hyper",
        "Mode_", "Pointer_", "braille_", "Sun",
    ];
    const EXACTLY: [&str; 38] = [
        "NoSymbol",
        "VoidSymbol",
        "Return",
        "BackSpace",
        "Tab",
        "Escape",
        "Delete",
        "Linefeed",
        "Clear",
        "Pause",
        "Scroll_Lock",
        "Sys_Req",
        "Print",
        "Insert",
        "Home",
        "End",
        "Prior",
        "Next",
        "Up",
        "Down",
        "Left",
        "Right",
        "Caps_Lock",
        "Num_Lock",
        "Undo",
        "Redo",
        "Find",
        "Help",
        "Cancel",
        "Menu",
        "Hangul",
        "Hangul_Hanja",
        "Hiragana",
        "Katakana",
        "Hiragana_Katakana",
        "Henkan_Mode",
        "Muhenkan",
        "Multi_key",
    ];
    PREFIXES.into_iter().any(|one| keysym.starts_with(one))
        || EXACTLY.contains(&keysym)
        || (keysym.starts_with('F') && keysym[1..].chars().all(char::is_numeric))
}
